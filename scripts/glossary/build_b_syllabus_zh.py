src = json.load(open(SRC))
missing = []
out = []
for u in src['units']:
    pts = []
    for g in u['grammar']:
        zh = G_ZH.get(g)
        if zh is None:
            missing.append((u['unit'], g))
        pts.append({'greek': g, 'zh': zh})           # 没配上就留 None, 前端只显示希腊语
    theme_zh = THEME_ZH.get(u['theme'])
    if u['theme'] and theme_zh is None:
        missing.append((u['unit'], f'[主题] {u["theme"]}'))
    out.append({
        'unit': u['unit'], 'system_unit': u['system_unit'],
        'title': u['title'], 'pages': u['pages'],
        'theme': u['theme'], 'theme_zh': theme_zh,
        'grammar': pts, 'exponents': u['exponents'], 'is_review': u['is_review'],
    })

