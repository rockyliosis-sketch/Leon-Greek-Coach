# -*- coding: utf-8 -*-
"""Ελληνικά Β PDF 老式希腊字形编码 -> 真实希腊字母.

这本 2012 年的书用的是 Mac 时代的自定义希腊字形编码, PDF 文字层里
存的不是 Unicode 希腊字母, 而是一串符号(∞ 代表 Α, · 代表 α ...).
必须逐字映射回来, 否则取出的"词"全是乱码.

注意: 书里有少数页是正常 Unicode 排的, 那些页 Δ 就是真的 Δ,
不能盲目映射 —— is_legacy() 用特征字符密度来区分.
"""
import re

M = {
 '∞':'Α','μ':'Β','°':'Γ','¢':'Δ','∂':'Ε','∑':'Ζ','∏':'Η','£':'Θ','π':'Ι','∫':'Κ',
 '§':'Λ','ª':'Μ','¡':'Ν','•':'Ξ','√':'Ο','¶':'Π','ƒ':'Ρ','™':'Σ','Δ':'Τ','À':'Υ',
 'º':'Φ','Ã':'Χ','æ':'Ψ','ø':'Ω',
 '·':'α','‚':'β','γ':'γ','Á':'γ','‰':'δ','Â':'ε','˙':'ζ','Ë':'η','ı':'θ','È':'ι',
 'Î':'κ','Ï':'λ','Ì':'μ','Ó':'ν','Í':'ξ','Ô':'ο','Ú':'ρ','Û':'σ','˜':'ς',
 'Ù':'τ','˘':'υ','Ê':'φ','¯':'χ','„':'ψ','ˆ':'ω',
 '\uf8ff':'π',   # 私有区字形, 终端里显示为空白, 手抄必丢 —— 用转义写死
 '¿':'ά','¤':'έ','‹':'ή','›':'ί','ﬁ':'ό','‡':'ύ','Ò':'ώ',
 '◊':'Ή','Œ':'Έ','Ÿ':'Ό','ñ':'•',
 # --- 2026-09-03 补: 原表漏掉的 5 个字形 ---
 # 漏这几个的后果是实词被写坏: προ˚όντος(应为 προϊόντος)、ÿσως(应为 Ίσως)、
 # τα˝ζω(应为 ταΐζω)、Õσε(应为 Άσε)、ﬂρα(应为 Ώρα), 全书约 250 处
 '˚':'ϊ',   # 分音符 iota
 '˝':'ΐ',   # 分音符+重音 iota
 'Õ':'Ά',   # 大写 alpha 带重音
 'ÿ':'Ί',   # 大写 iota 带重音
 'ﬂ':'Ώ',   # 大写 omega 带重音
}
# 映射表里有 4 个键本身就是真希腊字母, 含义要看上下文:
#   μ 在老编码里是 Β, 在正常文本里就是 μ;  π->Ι,  Δ->Τ,  γ->γ
# 判断一段文字是不是老编码, 只能靠其余那些"正常希腊文里绝不会出现"的字符。
AMBIGUOUS  = set('μγπΔ')
LEGACY_ONLY = set(M) - AMBIGUOUS

# 老编码页的特征字符（保留给旧调用方）
SIG = set('·˘ÌÙÂÈÔÚÛ‹ﬁ¿¤›‡Ò‚‰ÊÍ„ıÎÏÓ¯˙˜')

def is_legacy(txt):
    return sum(txt.count(c) for c in SIG) > 20

def is_legacy_seg(s):
    """这一小段是不是老编码 —— 只看无歧义字符"""
    return any(c in LEGACY_ONLY for c in s)

def dec(s):
    """逐行两级解码。

    为什么必须逐行、还要分两级:
      1) 书里有 29 页是混排的 —— 同一页上半截老编码、下半截正常 Unicode。
         整页解码会把正常那半毁掉: 真 μ 写成 Β、真 π 写成 Ι,
         συμφωνήσουμε 变成 συΒφωνήσουΒε。
      2) 有些正常 Unicode 行只是行首带一个老编码的项目符号(ñ = •),
         按"含老编码字符就整行解码"处理, 同样会毁掉这一行。
      所以: 无歧义字形(Ô È Ú ﬁ ...)永远解, 它们在正常希腊文里不可能出现;
            有歧义字形(μ γ π Δ 本身就是真希腊字母)只在整行有 >=3 个
            无歧义老编码字符、确认这是老编码行时才解。
    """
    out = []
    for ln in s.split('\n'):
        n_hard = sum(1 for c in ln if c in LEGACY_ONLY and c != 'ñ')
        full = n_hard >= 3
        out.append(''.join(
            M.get(c, c) if (full or c not in AMBIGUOUS) else c
            for c in ln))
    return '\n'.join(out)

# 行内混排到无法靠上下文判断时的兜底:
# 希腊语里, 一个小写词的中间不可能冒出大写 Β 或 Ι。
# 出现了就一定是上面那对有歧义字形没解开(真 μ 被留成 Β、真 π 被留成 Ι)。
_MIXED = re.compile(r'(?<=[α-ωά-ώϊϋΐΰ])[ΒΙ](?=[α-ωά-ώϊϋΐΰ])')
_FIX   = {'Β': 'μ', 'Ι': 'π'}

def fix_mixed(txt):
    return _MIXED.sub(lambda m: _FIX[m.group(0)], txt)
