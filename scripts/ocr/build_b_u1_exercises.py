def shuffle(ans, dis, seed):
    o = [ans] + list(dis)
    return [o[(i + seed) % len(o)] for i in range(len(o))]

rows, nid = [], 320700
def add(page, orig, stem_q, ans, dis, zh, tip, tag):
    global nid
    stem = stem_q if zh is None else f'{stem_q}\n（{zh}）'
    full = (f'【{tag}】{tip}\n【课本原句】{orig}\n'
            f'【出处】第 1 单元 {TITLE} · 课本第 {page} 页')
    base = dict(book_id='b1', unit=UNIT, unit_title=TITLE, page=page,
                skill_type=SK, question=stem, answer=ans, detailed_tip=full)
    rows.append(dict(id=nid, drill_type='choice', options=shuffle(ans, dis, nid % (len(dis)+1)),
                     translation=f'{tag} · 课本第 {page} 页', **base)); nid += 1
    rows.append(dict(id=nid, drill_type='cloze', options=None,
                     translation=f'{tag}（手写）· 课本第 {page} 页',
                     acceptable_answers=[ans, ans.lower(), ans.replace('’', "'")], **base)); nid += 1

