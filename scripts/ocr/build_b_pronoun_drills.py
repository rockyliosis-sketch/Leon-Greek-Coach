def opt_shuffle(ans, distractors, seed):
    """把正确答案混进干扰项, 位置由 id 决定 —— 同一道题每次打开顺序都一样, 不会忽左忽右。"""
    opts = [ans] + list(distractors)
    return [opts[(i + seed) % len(opts)] for i in range(len(opts))]


def accepts(ans):
    out = list(NU_PAIR.get(ans.lower(), [ans]))
    if ans[0].isupper():           # 句首大写形式也收小写
        out = [ans] + [x for x in out if x != ans] + [ans.lower()]
    seen, uniq = set(), []
    for x in out:
        if x.lower() not in seen:
            seen.add(x.lower()); uniq.append(x)
    return uniq


