def is_known(w):
    """A1/A2 已学?  三关: 原形表 -> 不规则形式表 -> 词干匹配"""
    n = norm(w)
    if n in known: return True
    if n in IRREG: return True
    k, how = mm.match(w)
    # match() 返回 'stem:xxx' / 'stem?:xxx', 不是裸 'stem'
    # (先前写成 how in ('exact','stem') 导致词干匹配全部失效, 基础词大量漏进候选)
    # 'stem?:' = 词干命中多个词典条目、无法确定是哪个。这里也算已学:
    # 宁可漏收一个新词, 不可让 Leon 去背他早就会的词。
    return bool(how)

# ---------- 逐单元扫描 ----------
rec = collections.defaultdict(lambda: {
    'forms': collections.Counter(), 'units': collections.Counter(),
    'first_page': 10**9, 'cap': 0, 'total': 0, 'example': None,
    'pages': collections.Counter()})

for u in M['units']:
    for p in u['pdf_pages']:
        txt = pages[p-1] if p-1 < len(pages) else ''
        bookpg = pdf2book.get(p, 0)
        for ln in txt.split('\n'):
            if NOISE.search(ln) or len(ln.strip()) < 2: continue
            for w in GREEK.findall(ln):
                n = norm(w)
                if len(n) < 3 or n in STOP or n in FRAGMENT or n in BASIC: continue
                if w.isupper(): continue                 # 全大写=标题/版式
                if is_known(w): continue                 # A1/A2 已学
                r = rec[n]
                r['forms'][w] += 1
                r['units'][u['unit']] += 1
                r['total'] += 1
                if w[0].isupper(): r['cap'] += 1
                if bookpg:
                    r['pages'][bookpg] += 1
                    if bookpg < r['first_page']: r['first_page'] = bookpg
                if r['example'] is None and 12 <= len(ln.strip()) <= 110:
                    r['example'] = ln.strip()

# ---------- 归并到候选条目 ----------
out = []
for n, r in rec.items():
    # 只出现一次的多为人名/笔误, 一般丢掉。
    # 但教材方框点名的词是例外 —— 教材白纸黑字说"这个要学", 哪怕正文只出现一次也留。
    # (方框提取的碎片如 'ίνω' 根本不在正文里, freq=0, 自然进不到这里, 不必额外过滤)
    if r['total'] < (1 if n in BOXED else 2): continue
    units = sorted(r['units'])
    out.append({
        'norm': n,
        'forms': [{'form': f, 'n': c} for f, c in r['forms'].most_common(6)],
        'total': r['total'],
        'units': units,
        'unit_main': r['units'].most_common(1)[0][0],     # 出现最多的单元 = 归属单元
        'unit_span': len(units),                          # 跨几个单元 = 通用度
        'first_page': r['first_page'] if r['first_page'] < 10**9 else None,
        'pages': sorted(r['pages']),
        'boxed': n in BOXED,                              # 教材点名
        'all_caps_start': r['cap'] == r['total'],         # 疑似专有名词
        'example': r['example'],
    })

out.sort(key=lambda x: (-x['boxed'], -x['unit_span'], -x['total']))
json.dump({'schema': 'b_candidates_v1',
           'note': 'B本候选新词证据表. 原形与中文由人工逐条确认, 本文件不含最终结论.',
           'total': len(out), 'candidates': out},
          open(f'{ROOT}/materials/glossaries/B_candidates.json', 'w'),
          ensure_ascii=False, indent=1)

print(f'候选(出现>=2次) {len(out)} 条')
print(f'  其中教材方框点名 {sum(1 for x in out if x["boxed"])} 条')
print(f'  疑似专有名词     {sum(1 for x in out if x["all_caps_start"])} 条')
print(f'  跨>=3单元(通用)  {sum(1 for x in out if x["unit_span"]>=3)} 条')
print('\n按归属单元:')
c = collections.Counter(x['unit_main'] for x in out)
for u in sorted(c): print(f'  U{u:>2}  {c[u]:>4}')
