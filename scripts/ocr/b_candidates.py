GREEK = re.compile(r'[Α-Ωα-ωΆ-Ώά-ώϊϋΐΰ]+')
NOISE = re.compile(r'Layout|GREEK|ΕΛΛΗΝΙΚΑ|protoselida|PARARTIMA|ενότητα\s*$')

