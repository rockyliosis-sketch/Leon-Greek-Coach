def opt_shuffle(ans, dis, seed):
    opts = [ans] + list(dis)
    return [opts[(i + seed) % len(opts)] for i in range(len(opts))]

bank = json.load(open(BANK))
kept = [d for d in bank['drills'] if d.get('skill_type') != 'dialogue']
nid = 320600
new = []
for page, orig, q, ans, dis, zh, tip in ITEMS:
    stem = f'{q}\n（{zh}）'
    full = (f'【情境交际金句】{tip}\n'
            f'【课本原句】{orig}\n'
            f'【出处】第 1 单元 {TITLE} · 「Πώς το λένε;」方框 · 课本第 {page} 页')
    base = dict(book_id='b1', unit=UNIT, unit_title=TITLE, page=page,
                skill_type='dialogue', question=stem, answer=ans, detailed_tip=full)
    new.append(dict(id=nid, drill_type='choice', options=opt_shuffle(ans, dis, nid % 4),
                    translation=f'情境交际金句 · 课本第 {page} 页', **base)); nid += 1
    new.append(dict(id=nid, drill_type='cloze', options=None,
                    translation=f'情境交际金句（手写）· 课本第 {page} 页',
                    acceptable_answers=[ans, ans.lower()] if ans[0].isupper() else [ans],
                    **base)); nid += 1

bank['drills'] = kept + new
