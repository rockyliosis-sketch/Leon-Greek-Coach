# 老编码页的特征字符（正常 Unicode 页不会有）
SIG = set('·˘ÌÙÂÈÔÚÛ‹ﬁ¿¤›‡Ò‚‰ÊÍ„ıÎÏÓ¯˙˜')
def is_legacy(txt):
    return sum(txt.count(c) for c in SIG) > 20
def dec(s):
    if not is_legacy(s):
        return s          # 正常 Unicode 页，原样返回（此时 Δ 就是真 Δ）
    return ''.join(M.get(c, c) for c in s)
